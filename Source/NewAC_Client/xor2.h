template <int XORSTART, int BUFLEN>
class XorStr
{
private:
	XorStr();
public:
	char* s;
	wchar_t* ws;
	XorStr(const char* xs);

	static void operator delete(void* ptr, size_t sz)
	{
		XorStr* str = (XorStr*)ptr;
		if (str->s)
			free(str->s);
		if (str->ws)
			free(str->ws);
		free(ptr);
	}
};

template <int XORSTART, int BUFLEN>
XorStr<XORSTART, BUFLEN>::XorStr(const char* xs)
{
	s = (char*)calloc(BUFLEN, sizeof(char));
	ws = (wchar_t*)calloc(BUFLEN, sizeof(wchar_t));
	int xvalue = XORSTART;
	int i = 0;

	for (; i < (BUFLEN - 1); i++)
	{
		s[i] = xs[i] ^ xvalue;
		xvalue += 1;
		xvalue %= 256;
	}

	s[BUFLEN - 1] = 0;
	MultiByteToWideChar(CP_UTF8, 0, s, BUFLEN - 1, ws, BUFLEN - 1);
	ws[BUFLEN - 1] = 0;
}

